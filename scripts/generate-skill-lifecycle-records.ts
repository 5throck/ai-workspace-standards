export type RecordKind = "projected" | "derived";

export interface PlannedRecord {
  /** Group the record belongs to: "common", a co-* variant name, or "project". */
  group: string;
  skill: string;
  /** Repo-relative output path (relative to the tree root, or the project root in --project mode). */
  path: string;
  kind: RecordKind;
  content: string;
}

export interface PlanProblem {
  group: string;
  skill: string;
  message: string;
}

export interface Plan {
  records: PlannedRecord[];
  /** Skills whose record is hand-authored (existing unmarked file) and left untouched. */
  handAuthored: Array<{ group: string; skill: string; path: string }>;
  problems: PlanProblem[];
}

export interface SkillDir {
  name: string;
  skillMd: string;
}

/** Skill directories (flat layout) that contain a direct SKILL.md. */
export function listSkillDirs(tree: Tree, skillsRel: string): SkillDir[] {
  return tree
    .readDir(skillsRel)
    .filter(
      (e) => e.isDir && !e.name.startsWith("_") && e.name !== "local" && e.name !== "external" && e.name !== "_archive",
    )
    .filter((e) => tree.read(`${skillsRel}/${e.name}/SKILL.md`) !== null)
    .map((e) => ({ name: e.name, skillMd: `${skillsRel}/${e.name}/SKILL.md` }))
    .sort((a, b) => (a.name < b.name ? -1 : 1));
}

function templateVariants(tree: Tree): string[] {
  return tree
    .readDir("templates")
    .filter((e) => e.isDir && e.name.startsWith("co-"))
    .map((e) => e.name)
    .sort();
}

/** Plan the template-side records: common projections and variant-own derivations. */
export function planTemplateRecords(tree: Tree, ownerMap: OwnerMap): Plan {
  const plan: Plan = { records: [], handAuthored: [], problems: [] };
  const commonSkills = listSkillDirs(tree, "templates/common/skills");
  const commonNames = new Set(commonSkills.map((s) => s.name));
  const commonRecordDir = `templates/common/${RECORD_DIR}`;

  for (const s of commonSkills) {
    const path = `${commonRecordDir}/${s.name}.md`;
    const existing = tree.read(path);
    if (existing !== null && !isGeneratedRecord(existing)) {
      plan.handAuthored.push({ group: "common", skill: s.name, path });
      continue;
    }
    const l0 = tree.read(`${RECORD_DIR}/${s.name}.md`);
    const fm = parseSkillFrontmatter(tree.read(s.skillMd));
    const res =
      l0 !== null
        ? projectRecord({
            skill: s.name,
            l0Record: l0,
            frontmatter: fm,
            ownerMap,
            commonPathExists: (rel) => tree.exists(`templates/common/${rel}`),
          })
        : deriveRecord({ skill: s.name, variant: "common", frontmatter: fm, ownerMap });
    if (!res.ok) plan.problems.push({ group: "common", skill: s.name, message: res.reason });
    else
      plan.records.push({
        group: "common",
        skill: s.name,
        path,
        kind: l0 !== null ? "projected" : "derived",
        content: res.content,
      });
  }

  for (const variant of templateVariants(tree)) {
    const recordDir = `templates/${variant}/${RECORD_DIR}`;
    for (const s of listSkillDirs(tree, `templates/${variant}/skills`)) {
      if (commonNames.has(s.name)) continue; // covered by the common record
      const path = `${recordDir}/${s.name}.md`;
      const existing = tree.read(path);
      if (existing !== null && !isGeneratedRecord(existing)) {
        plan.handAuthored.push({ group: variant, skill: s.name, path });
        continue;
      }
      const fm = parseSkillFrontmatter(tree.read(s.skillMd));
      const res = deriveRecord({ skill: s.name, variant, frontmatter: fm, ownerMap });
      if (!res.ok) plan.problems.push({ group: variant, skill: s.name, message: res.reason });
      else plan.records.push({ group: variant, skill: s.name, path, kind: "derived", content: res.content });
    }
  }
  return plan;
}

/**
 * Plan records for a project's local skills (--project): every active or experimental skill that is
 * neither in the common set nor already recorded. Output paths are relative to the project root.
 */
export function planProjectRecords(opts: {
  projectTree: Tree;
  commonSkillNames: Set<string>;
  ownerMap: OwnerMap;
  variant?: string;
}): Plan {
  const plan: Plan = { records: [], handAuthored: [], problems: [] };
  const variant = opts.variant ?? "project";
  for (const s of listSkillDirs(opts.projectTree, "skills")) {
    if (opts.commonSkillNames.has(s.name)) continue;
    const fm = parseSkillFrontmatter(opts.projectTree.read(s.skillMd));
    const status = statusOf(fm, "active");
    if (status !== "active" && status !== "experimental") continue;
    const path = `${RECORD_DIR}/${s.name}.md`;
    const existing = opts.projectTree.read(path);
    if (existing !== null && !isGeneratedRecord(existing)) {
      plan.handAuthored.push({ group: "project", skill: s.name, path });
      continue;
    }
    const res = deriveRecord({ skill: s.name, variant, frontmatter: fm, ownerMap: opts.ownerMap });
    if (!res.ok) plan.problems.push({ group: "project", skill: s.name, message: res.reason });
    else plan.records.push({ group: "project", skill: s.name, path, kind: "derived", content: res.content });
  }
  return plan;
}

// ---------------------------------------------------------------------------
// Check (parity) and orphan detection
// ---------------------------------------------------------------------------

export interface CheckFinding {
  kind: "missing" | "stale" | "orphan";
  path: string;
  group: string;
  skill: string;
}

/** Compare the plan against the tree byte for byte; orphan = generated-marker file with no planned record. */
export function checkPlan(tree: Tree, plan: Plan, scanDirs: string[]): CheckFinding[] {
  const out: CheckFinding[] = [];
  const planned = new Set(plan.records.map((r) => r.path));
  for (const r of plan.records) {
    const existing = tree.read(r.path);
    if (existing === null) out.push({ kind: "missing", path: r.path, group: r.group, skill: r.skill });
    else if (existing !== r.content) out.push({ kind: "stale", path: r.path, group: r.group, skill: r.skill });
  }
  for (const dir of scanDirs) {
    for (const e of tree.readDir(dir)) {
      if (e.isDir || !e.name.endsWith(".md")) continue;
      const path = `${dir}/${e.name}`;
      if (planned.has(path)) continue;
      const content = tree.read(path);
      if (content !== null && isGeneratedRecord(content))
        out.push({ kind: "orphan", path, group: dir, skill: e.name.replace(/\.md$/, "") });
    }
  }
  return out.sort((a, b) => (a.path < b.path ? -1 : 1));
}

export function templateRecordDirs(tree: Tree): string[] {
  return ["common", ...templateVariants(tree)].map((v) => `templates/${v}/${RECORD_DIR}`);
}

