const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function loadOwnerMap(root: string): OwnerMap {
  const p = join(root, "scripts", "data", "skill-owner-map.json");
  return parseOwnerMap(existsSync(p) ? readFileSync(p, "utf-8") : null);
}

function summarize(plan: Plan): string {
  const byGroup = new Map<string, { projected: number; derived: number }>();
  for (const r of plan.records) {
    const g = byGroup.get(r.group) ?? { projected: 0, derived: 0 };
    g[r.kind]++;
    byGroup.set(r.group, g);
  }
  const lines = [...byGroup.entries()].sort().map(([g, c]) => `  ${g}: ${c.projected} projected, ${c.derived} derived`);
  const projected = plan.records.filter((r) => r.kind === "projected").length;
  lines.push(
    `  total: ${plan.records.length} record(s) (${projected} projected, ${plan.records.length - projected} derived); ${plan.handAuthored.length} hand-authored left alone; ${plan.problems.length} problem(s)`,
  );
  return lines.join("\n");
}

export function main(argv: string[], root: string = ROOT): number {
  const check = argv.includes("--check");
  const write = argv.includes("--write");
  const pi = argv.indexOf("--project");
  const projectArg = pi >= 0 ? argv[pi + 1] : undefined;
  if (pi >= 0 && (!projectArg || projectArg.startsWith("--"))) {
    console.error("--project requires a path");
    return 2;
  }
  if (check && write) {
    console.error("--check and --write are mutually exclusive");
    return 2;
  }
  const ownerMap = loadOwnerMap(root);
  const rootTree = fsTree(root);

  let plan: Plan;
  let baseDir: string;
  let scanDirs: string[];
  let tree: Tree;
  if (projectArg) {
    baseDir = resolve(projectArg);
    tree = fsTree(baseDir);
    const common = new Set(listSkillDirs(rootTree, "templates/common/skills").map((s) => s.name));
    plan = planProjectRecords({ projectTree: tree, commonSkillNames: common, ownerMap });
    scanDirs = [RECORD_DIR];
  } else {
    baseDir = root;
    tree = rootTree;
    plan = planTemplateRecords(tree, ownerMap);
    scanDirs = templateRecordDirs(tree);
  }

  for (const p of plan.problems) console.error(`[PROBLEM] ${p.group}/${p.skill}: ${p.message}`);
  if (plan.problems.length > 0) return 1;

  if (check) {
    const findings = checkPlan(tree, plan, scanDirs);
    for (const f of findings.slice(0, 40)) console.log(`[${f.kind.toUpperCase()}] ${f.path}`);
    if (findings.length > 40) console.log(`... +${findings.length - 40} more`);
    console.log(summarize(plan));
    console.log(
      findings.length === 0
        ? "generate --check: all generated records reproduce byte for byte"
        : `generate --check: ${findings.length} finding(s)`,
    );
    return findings.length === 0 ? 0 : 1;
  }
  if (write) {
    let written = 0;
    for (const r of plan.records) {
      const abs = join(baseDir, r.path);
      if (existsSync(abs) && readFileSync(abs, "utf-8").replace(/\r\n/g, "\n") === r.content) continue;
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, r.content);
      written++;
    }
    console.log(summarize(plan));
    console.log(`generate --write: wrote ${written} file(s)`);
    return 0;
  }
  console.log("generate (dry run, nothing written):");
  console.log(summarize(plan));
  return 0;
}

if (import.meta.main) {
  process.exit(main(process.argv.slice(2)));
}
