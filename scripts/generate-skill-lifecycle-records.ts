// SLR evaluation (validate-templates check SLR)
// ---------------------------------------------------------------------------

export type SlrRule = "coverage" | "parity" | "leak" | "owner" | "owner-agent";

export interface SlrFinding {
  rule: SlrRule;
  /** "common" or a co-* variant. */
  variant: string;
  path: string;
  /** Skill (or record) name used in grouped report lines. */
  name: string;
  message: string;
}

function agentNames(tree: Tree, rel: string): string[] {
  return walkFiles(tree, rel)
    .filter((f) => f.endsWith(".md"))
    .map((f) => f.slice(f.lastIndexOf("/") + 1).replace(/\.md$/, ""));
}

export interface SlrResult {
  findings: SlrFinding[];
  checkedSkills: number;
  plan: Plan;
}

/**
 * Evaluate the four SLR rules over a template tree (design 4.6):
 *  coverage: every active skill has a record in its own or the common record directory;
 *  parity: every generated record reproduces byte for byte (and no orphan generated record exists);
 *  leak: no record file carries an L0-internal reference;
 *  owner: every skill resolves an owner (D5) and the owner exists as an agent.
 */
export function evaluateSlr(tree: Tree, ownerMap: OwnerMap): SlrResult {
  const findings: SlrFinding[] = [];
  const plan = planTemplateRecords(tree, ownerMap);
  const variants = templateVariants(tree);
  const commonDir = `templates/common/${RECORD_DIR}`;
  const rosterBase = new Set<string>([...agentNames(tree, "agents"), ...agentNames(tree, "templates/common/agents")]);
  // A common skill is delivered to every project, so its owner must exist in the common roster
  // (templates/common/agents: pm and the common skill-owner agents). Variant-only and L0 root
  // agents do not count (common-agents design 2026-11-12, CA-1, D4). Variant-own skills use the
  // variant + common + workspace roster.
  const commonRoster = new Set<string>(agentNames(tree, "templates/common/agents"));
  let checkedSkills = 0;

  const groups: Array<{ variant: string; skills: SkillDir[] }> = [
    { variant: "common", skills: listSkillDirs(tree, "templates/common/skills") },
    ...variants.map((v) => ({ variant: v, skills: listSkillDirs(tree, `templates/${v}/skills`) })),
  ];

  for (const g of groups) {
    const ownDir = `templates/${g.variant}/${RECORD_DIR}`;
    const roster = new Set<string>(g.variant === "common" ? commonRoster : rosterBase);
    if (g.variant !== "common") for (const n of agentNames(tree, `templates/${g.variant}/agents`)) roster.add(n);
    for (const s of g.skills) {
      checkedSkills++;
      const fm = parseSkillFrontmatter(tree.read(s.skillMd));
      const status = statusOf(fm, "");
      const hasRecord = tree.exists(`${ownDir}/${s.name}.md`) || tree.exists(`${commonDir}/${s.name}.md`);
      if (status === "active" && !hasRecord) {
        findings.push({
          rule: "coverage",
          variant: g.variant,
          path: `${ownDir}/${s.name}.md`,
          name: s.name,
          message: `${g.variant}: no lifecycle record for active skill ${s.name}`,
        });
      }
      const owner = resolveOwner({ variant: g.variant, skill: s.name, frontmatter: fm, ownerMap });
      if (!owner.ok) {
        findings.push({ rule: "owner", variant: g.variant, path: s.skillMd, name: s.name, message: owner.reason });
      } else if (!roster.has(owner.owner)) {
        findings.push({
          rule: "owner-agent",
          variant: g.variant,
          path: s.skillMd,
          name: s.name,
          message:
            g.variant === "common"
              ? `common/${s.name}: owner "${owner.owner}" is not in the common roster (templates/common/agents)`
              : `${g.variant}/${s.name}: owner "${owner.owner}" is not an agent in the variant, common, or workspace roster`,
        });
      }
    }
  }

  for (const f of checkPlan(tree, plan, templateRecordDirs(tree))) {
    if (f.kind === "missing") continue; // reported by coverage when the skill is active
    findings.push({
      rule: "parity",
      variant: f.group.startsWith("templates/") ? f.group.split("/")[1] : f.group,
      path: f.path,
      name: f.skill,
      message:
        f.kind === "stale"
          ? `${f.path} differs from the regenerated record — run bun scripts/generate-skill-lifecycle-records.ts --write (never hand-edit a generated record)`
          : `${f.path} carries the generated marker but no skill produces it`,
    });
  }
  for (const p of plan.problems) {
    // Owner problems are already reported by the owner rule; keep any other generation problem visible.
    if (!/^no owner for /.test(p.message))
      findings.push({ rule: "parity", variant: p.group, path: p.skill, name: p.skill, message: p.message });
  }

  for (const dir of templateRecordDirs(tree)) {
    for (const e of tree.readDir(dir)) {
      if (e.isDir || !e.name.endsWith(".md")) continue;
      const path = `${dir}/${e.name}`;
      const content = tree.read(path) ?? "";
      const bad = content.split("\n").find((l) => isInternalRef(l));
      if (bad !== undefined) {
        findings.push({
          rule: "leak",
          variant: dir.split("/")[1],
          path,
          name: e.name.replace(/\.md$/, ""),
          message: `${path} references an L0-internal artifact that does not resolve in a project: "${bad.trim().slice(0, 80)}"`,
        });
      }
    }
  }
  return { findings, checkedSkills, plan };
}

export interface SlrFlag {
  enforce: boolean;
}

export function parseEnforcementFlag(raw: string | null): SlrFlag {
  if (raw === null || raw.trim() === "") return { enforce: false };
  const v = JSON.parse(raw) as { enforce?: unknown };
  return { enforce: v.enforce === true };
}

export interface SlrGroupedFinding {
  rule: SlrRule;
  variant: string;
  count: number;
  message: string;
}

/** One line per (rule, variant) so a 188-record gap stays readable. */
export function groupSlrFindings(findings: SlrFinding[], listMax = 6): SlrGroupedFinding[] {
  const groups = new Map<string, SlrFinding[]>();
  for (const f of findings) {
    const k = `${f.rule}\u0000${f.variant}`;
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k)!.push(f);
  }
  const out: SlrGroupedFinding[] = [];
  for (const [k, list] of [...groups.entries()].sort()) {
    const [rule, variant] = k.split("\u0000") as [SlrRule, string];
    const names = list
      .slice(0, listMax)
      .map((f) => f.name)
      .join(", ");
    const more = list.length > listMax ? `, +${list.length - listMax} more` : "";
    out.push({
      rule,
      variant,
      count: list.length,
      message:
        list.length === 1 ? list[0].message : `SLR ${rule}: ${list.length} finding(s) in ${variant} (${names}${more})`,
    });
  }
  return out;
}

export const SLR_FIX: Record<SlrRule, string> = {
  coverage:
    "Run bun scripts/generate-skill-lifecycle-records.ts --write (the records are published by the templates PR, never hand-written)",
  parity:
    "Run bun scripts/generate-skill-lifecycle-records.ts --write to regenerate; drop the generated marker to make a record hand-owned",
  leak: "Remove the L0-internal reference (ADR/DEC/ticket ids, docs/designs|decisions|adr|reports, tickets/) from the record",
  owner: "Add owner: to the SKILL.md frontmatter, or an entry to scripts/data/skill-owner-map.json",
  "owner-agent": "Fix the owner so it names an existing agent (variant, common, or workspace roster)",
};

export interface SlrIssue {
  level: "error" | "warning";
  variant: string;
  check: string;
  message: string;
  fix: string;
}

/**
 * Map SLR findings to validator issues (D11): `enforce` false reports warnings (exit 0), true
 * reports errors (blocking). The flag is an argument so tests never touch the config file.
 */
export function slrIssues(findings: SlrFinding[], enforce: boolean): SlrIssue[] {
  return groupSlrFindings(findings).map((g) => ({
    level: enforce ? "error" : "warning",
    variant: g.variant,
    check: `skill-record-${g.rule}`,
    message: g.message,
    fix: SLR_FIX[g.rule],
  }));
}

