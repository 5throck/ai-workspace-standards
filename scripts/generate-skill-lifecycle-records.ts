interface RenderInput {
  skill: string;
  status: string;
  owner: string;
  created: string;
  description: string;
  dependencies: string[];
  phaseReason: string;
  phaseApprover: string;
  acceptance: string;
}

function renderRecord(r: RenderInput): string {
  const parts: string[] = [
    GENERATED_MARKER,
    `# ${r.skill} Skill Lifecycle`,
    "## Metadata\n\n" +
      `- **Skill**: ${r.skill}\n- **Status**: ${r.status}\n- **Owner**: ${r.owner}\n- **Created**: ${r.created}`,
    `## Description\n\n${r.description}`,
  ];
  if (r.dependencies.length > 0) parts.push(`## Dependencies\n\n${r.dependencies.join("\n")}`);
  parts.push(
    "## Phase History\n\n| Date | From | To | Reason | Approver |\n|------|------|----|--------|----------|\n" +
      `| ${r.created} | - | ${phaseName(r.status)} | ${r.phaseReason} | ${r.phaseApprover} |`,
  );
  parts.push(`## Acceptance Criteria\n\n${r.acceptance}`);
  return parts.join("\n\n") + "\n";
}

function standardAcceptance(skill: string, owner: string): string {
  return [
    "### Production Phase",
    "",
    `- [x] Skill SKILL.md exists at \`skills/${skill}/SKILL.md\``,
    "- [x] Frontmatter valid: name, description, status, scope, version, owner populated",
    `- [x] Owner assigned: ${owner}`,
  ].join("\n");
}

const UNRECORDED = "unrecorded";

export type RecordResult = { ok: true; content: string } | { ok: false; reason: string };

/** Projection of an L0 record for a common skill (design 4.2, mechanism 1). */
export function projectRecord(opts: {
  skill: string;
  l0Record: string;
  frontmatter: Frontmatter | null;
  ownerMap: OwnerMap;
  /** Existence check relative to templates/common/ (Dependencies keep only paths that resolve there). */
  commonPathExists: (rel: string) => boolean;
}): RecordResult {
  const owner = resolveOwner({
    variant: "common",
    skill: opts.skill,
    frontmatter: opts.frontmatter,
    ownerMap: opts.ownerMap,
  });
  if (!owner.ok) return { ok: false, reason: owner.reason };
  const rec = parseRecord(opts.l0Record);

  const created =
    rec.kv.get("created")?.match(DATE_RE)?.[0] ??
    trimBlock(rec.sections.get("created") ?? []).match(DATE_RE)?.[0] ??
    trimBlock(rec.sections.get("phase history") ?? []).match(DATE_RE)?.[0] ??
    fmDate(opts.frontmatter) ??
    UNRECORDED;

  const description =
    sanitizeText(trimBlock(rec.sections.get("description") ?? [])).trim() ||
    sanitizeText(foldDescription(opts.frontmatter)).trim() ||
    "No description recorded.";

  const dependencies = (rec.sections.get("dependencies") ?? [])
    .filter((l) => l.trim() !== "")
    .filter((l) => !isInternalRef(l))
    .filter((l) => pathsInLine(l).every((p) => opts.commonPathExists(p)))
    .map((l) => l.trimEnd());

  // First Phase History entry: table data row or the first bullet; sanitized and flattened.
  let reason = "";
  let approver = owner.owner;
  const phaseLines = (rec.sections.get("phase history") ?? []).filter((l) => l.trim() !== "");
  const dataRow = phaseLines.find(
    (l) => l.trim().startsWith("|") && !/^\|[\s|:-]+\|?$/.test(l.trim()) && !/^\|\s*Date\s*\|/i.test(l.trim()),
  );
  if (dataRow) {
    const cells = dataRow
      .trim()
      .replace(/^\||\|$/g, "")
      .split("|")
      .map((c) => c.trim());
    reason = cells.length >= 4 ? cells[3] : "";
    if (cells.length >= 5 && cells[4] !== "") approver = oneLine(cells[4]);
  } else if (phaseLines.length > 0) {
    reason = phaseLines[0].replace(/^[-*]\s+/, "");
  }
  reason = oneLine(sanitizeText(reason)) || "Initial production record";

  const acceptanceSrc = sanitizeText(trimBlock(rec.sections.get("acceptance criteria") ?? []));
  const hasCriteria = acceptanceSrc.split("\n").some((l) => /^\s*(?:[-*]|\d+\.)\s+\S/.test(l));
  const status = statusOf(opts.frontmatter, rec.kv.get("status") ?? "active");

  return {
    ok: true,
    content: finalizeClean(
      renderRecord({
        skill: opts.skill,
        status,
        owner: owner.owner,
        created,
        description,
        dependencies,
        phaseReason: reason,
        phaseApprover: approver,
        acceptance: hasCriteria ? acceptanceSrc : standardAcceptance(opts.skill, owner.owner),
      }),
    ),
  };
}

/** Last-line guard: no output line may still carry an internal reference. */
function finalizeClean(content: string): string {
  return content
    .split("\n")
    .filter((l) => l === GENERATED_MARKER || !isInternalRef(l))
    .join("\n");
}

/** Derivation from SKILL.md frontmatter (variant-own and project-local skills). */
export function deriveRecord(opts: {
  skill: string;
  variant: string;
  frontmatter: Frontmatter | null;
  ownerMap: OwnerMap;
}): RecordResult {
  const owner = resolveOwner({
    variant: opts.variant,
    skill: opts.skill,
    frontmatter: opts.frontmatter,
    ownerMap: opts.ownerMap,
  });
  if (!owner.ok) return { ok: false, reason: owner.reason };
  const status = statusOf(opts.frontmatter, "active");
  const created = fmDate(opts.frontmatter) ?? UNRECORDED;
  const description = sanitizeText(foldDescription(opts.frontmatter)).trim() || "No description recorded.";
  return {
    ok: true,
    content: finalizeClean(
      renderRecord({
        skill: opts.skill,
        status,
        owner: owner.owner,
        created,
        description,
        dependencies: [],
        phaseReason: "Initial record derived from SKILL.md frontmatter",
        phaseApprover: owner.owner,
        acceptance: standardAcceptance(opts.skill, owner.owner),
      }),
    ),
  };
}

export function isGeneratedRecord(content: string): boolean {
  return content.split("\n", 1)[0] === GENERATED_MARKER;
}

