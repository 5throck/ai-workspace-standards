interface ParsedRecord {
  sections: Map<string, string[]>;
  kv: Map<string, string>;
}

function parseRecord(text: string): ParsedRecord {
  const sections = new Map<string, string[]>();
  const kv = new Map<string, string>();
  let current: string | null = null;
  for (const line of text.replace(/\r\n/g, "\n").split("\n")) {
    const h = line.match(/^##\s+(.+?)\s*$/);
    if (h) {
      current = h[1].toLowerCase();
      if (!sections.has(current)) sections.set(current, []);
      continue;
    }
    if (current !== null) sections.get(current)!.push(line);
    const k = line.match(/^\s*-\s+\*\*([^*]+)\*\*:\s*(.*)$/);
    if (k && !kv.has(k[1].trim().toLowerCase())) kv.set(k[1].trim().toLowerCase(), k[2].trim());
  }
  return { sections, kv };
}

function trimBlock(lines: string[]): string {
  return lines.join("\n").replace(/^\n+|\n+$/g, "");
}

const DATE_RE = /\d{4}-\d{2}-\d{2}/;

function oneLine(s: string): string {
  return s.replace(/\s+/g, " ").replace(/\|/g, "/").trim();
}

function fmDate(fm: Frontmatter | null): string | null {
  if (!fm) return null;
  const meta = fm.metadata && typeof fm.metadata === "object" ? (fm.metadata as Record<string, unknown>) : {};
  for (const src of [fm, meta]) {
    for (const k of ["created", "last_reviewed", "last_updated"]) {
      const v = src[k];
      if (typeof v === "string" && DATE_RE.test(v)) return v.match(DATE_RE)![0];
    }
  }
  return null;
}

function foldDescription(fm: Frontmatter | null): string {
  const d = fm?.description;
  return typeof d === "string" ? d.replace(/\s+/g, " ").trim() : "";
}

function statusOf(fm: Frontmatter | null, fallback: string): string {
  const s = fm?.status;
  return typeof s === "string" && s.trim() !== "" ? s.trim() : fallback;
}

function phaseName(status: string): string {
  return status === "active" ? "production" : status;
}

