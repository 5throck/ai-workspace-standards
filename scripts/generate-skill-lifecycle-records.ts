#!/usr/bin/env bun
/**
 * generate-skill-lifecycle-records.ts — Skill lifecycle record generator and SLR evaluator.
 *
 * Design: docs/designs/2026-11-12-skill-lifecycle-record-delivery-design.md (U-20261112-005,
 * PR-1 of 3). Delivered skills must arrive with a lifecycle record
 * (docs/lifecycle/skills/<name>.md) so Check LC stays silent in projects.
 *
 * Two record forms (design 4.2, D1):
 *   - projection: a sanitized, version-free reduction of the L0 record of a common skill
 *     (L0-internal references removed sentence by sentence, Version/Changelog/Notes dropped).
 *   - derivation: a record built from the SKILL.md frontmatter (variant-own skills, and
 *     project-local skills via --project).
 * Every generated file starts with GENERATED_MARKER. The generator never touches a file that
 * lacks the marker (hand-authored records stay hand-owned).
 *
 * Owner resolution (D5): frontmatter `owner:` first, then the explicit table
 * scripts/data/skill-owner-map.json ({ "<variant>/<skill>": agent, "*\/<skill>": agent }), else
 * failure. There is no default owner.
 *
 * Usage:
 *   bun scripts/generate-skill-lifecycle-records.ts                  # dry run: counts per group
 *   bun scripts/generate-skill-lifecycle-records.ts --check          # exit 1 when any generated record is missing/stale/orphaned
 *   bun scripts/generate-skill-lifecycle-records.ts --write          # write records under templates/
 *   bun scripts/generate-skill-lifecycle-records.ts --project <path> [--check|--write]
 *                                                                    # derive records for a project's local skills
 *
 * The core is pure over an injected Tree so unit tests run on in-memory file maps. The CLI is
 * the only place that touches the real filesystem.
 *
 * @version 1.1.0
 *
 * v1.1.0 (2026-11-12, common-agents CA-1): owner-agent rule is STRICT for common skills: the owner
 *         must exist in templates/common/agents (no variant-union leniency). Severity still follows
 *         scripts/skill-record-enforcement.json (enforce:false WARN, enforce:true error).
 * v1.0.0 (2026-11-12, U-20261112-005 PR-1): initial — projection, derivation, owner
 *         resolution, --check / --write / --project, SLR evaluation (coverage, parity, leak,
 *         owner) consumed by validate-templates.ts check SLR.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { load, JSON_SCHEMA } from "js-yaml";
import { L0_INTERNAL_REF_PATTERN, L0_REF_PATTERN } from "./helpers/l0-ref-policy.ts";

export const GENERATED_MARKER =
  "<!-- generated by scripts/generate-skill-lifecycle-records.ts — hand edits are overwritten at the next publish -->";

const RECORD_DIR = "docs/lifecycle/skills";

// ---------------------------------------------------------------------------
// Tree abstraction (real fs for the CLI, in-memory map for tests)
// ---------------------------------------------------------------------------

export interface TreeEntry {
  name: string;
  isDir: boolean;
}

export interface Tree {
  /** Directory entries, or [] when the directory does not exist. */
  readDir(rel: string): TreeEntry[];
  /** File content, or null when absent. */
  read(rel: string): string | null;
  /** True for an existing file or directory. */
  exists(rel: string): boolean;
}

export function fsTree(root: string): Tree {
  return {
    readDir(rel) {
      const abs = join(root, rel);
      if (!existsSync(abs)) return [];
      try {
        return readdirSync(abs, { withFileTypes: true }).map((e) => ({ name: e.name, isDir: e.isDirectory() }));
      } catch {
        return [];
      }
    },
    read(rel) {
      const abs = join(root, rel);
      return existsSync(abs) ? readFileSync(abs, "utf-8").replace(/\r\n/g, "\n") : null;
    },
    exists: (rel) => existsSync(join(root, rel)),
  };
}

/** In-memory tree over a { "rel/path": content } map; directories are derived from the keys. */
export function mapTree(files: Record<string, string>): Tree {
  const keys = Object.keys(files);
  return {
    readDir(rel) {
      const prefix = rel === "" ? "" : rel.replace(/\/+$/, "") + "/";
      const seen = new Map<string, boolean>();
      for (const k of keys) {
        if (!k.startsWith(prefix)) continue;
        const rest = k.slice(prefix.length);
        const slash = rest.indexOf("/");
        if (slash === -1) seen.set(rest, false);
        else seen.set(rest.slice(0, slash), true);
      }
      return [...seen.entries()].map(([name, isDir]) => ({ name, isDir }));
    },
    read: (rel) => (rel in files ? files[rel] : null),
    exists(rel) {
      const r = rel.replace(/\/+$/, "");
      return r in files || keys.some((k) => k.startsWith(r + "/"));
    },
  };
}

function walkFiles(tree: Tree, rel: string): string[] {
  const out: string[] = [];
  for (const e of tree.readDir(rel).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const child = rel === "" ? e.name : `${rel}/${e.name}`;
    if (e.isDir) out.push(...walkFiles(tree, child));
    else out.push(child);
  }
  return out;
}

