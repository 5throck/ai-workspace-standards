export type Frontmatter = Record<string, unknown>;

export function parseSkillFrontmatter(text: string | null): Frontmatter | null {
  if (text === null) return null;
  const m = text.replace(/\r\n/g, "\n").match(/^---\n([\s\S]*?)\n---(?:\n|$)/);
  if (!m) return null;
  try {
    const v = load(m[1], { schema: JSON_SCHEMA });
    return v && typeof v === "object" && !Array.isArray(v) ? (v as Frontmatter) : null;
  } catch {
    return null;
  }
}

export type OwnerMap = Record<string, string>;

export function parseOwnerMap(raw: string | null): OwnerMap {
  if (raw === null || raw.trim() === "") return {};
  const v = JSON.parse(raw) as unknown;
  if (!v || typeof v !== "object" || Array.isArray(v)) throw new Error("skill-owner-map.json must be a JSON object");
  const out: OwnerMap = {};
  for (const [k, val] of Object.entries(v as Record<string, unknown>)) {
    if (k.startsWith("_")) continue; // comment keys
    if (typeof val !== "string" || val.trim() === "")
      throw new Error(`skill-owner-map.json: value for "${k}" must be a non-empty string`);
    out[k] = val.trim();
  }
  return out;
}

export type OwnerResolution =
  | { ok: true; owner: string; source: "frontmatter" | "map" }
  | { ok: false; reason: string };

/** D5: frontmatter owner, then explicit map ("<variant>/<skill>" then "*\/<skill>"), else failure. */
export function resolveOwner(opts: {
  variant: string;
  skill: string;
  frontmatter: Frontmatter | null;
  ownerMap: OwnerMap;
}): OwnerResolution {
  const fmOwner = opts.frontmatter?.owner;
  if (typeof fmOwner === "string" && fmOwner.trim() !== "")
    return { ok: true, owner: fmOwner.trim(), source: "frontmatter" };
  const mapped = opts.ownerMap[`${opts.variant}/${opts.skill}`] ?? opts.ownerMap[`*/${opts.skill}`];
  if (mapped) return { ok: true, owner: mapped, source: "map" };
  return {
    ok: false,
    reason: `no owner for ${opts.variant}/${opts.skill}: SKILL.md frontmatter has no owner and scripts/data/skill-owner-map.json has no entry`,
  };
}

// ---------------------------------------------------------------------------
// Sanitization
// ---------------------------------------------------------------------------

export function isInternalRef(text: string): boolean {
  return L0_INTERNAL_REF_PATTERN.test(text) || L0_REF_PATTERN.test(text);
}

function filterSentences(text: string): string {
  return text
    .split(/(?<=[.!?])\s+/)
    .filter((s) => !isInternalRef(s))
    .join(" ")
    .trim();
}

const LIST_PREFIX = /^(\s*(?:[-*]|\d+\.)(?:\s+\[[ xX]\])?\s+)(.*)$/;

/**
 * Drop every sentence that carries an L0-internal reference. A paragraph that carries one is
 * rejoined into a single line (so no half-sentence is left behind); clean paragraphs keep their
 * original line breaks. List items are filtered on their own; a heading or table row that carries a
 * reference is dropped. Lines left empty are removed.
 */
export function sanitizeText(text: string): string {
  const out: string[] = [];
  let para: string[] = [];
  const flush = () => {
    if (para.length === 0) return;
    const joined = para.map((l) => l.trim()).join(" ");
    if (!isInternalRef(joined)) out.push(para.join("\n"));
    else {
      const kept = filterSentences(joined);
      if (kept !== "") out.push(kept);
    }
    para = [];
  };
  for (const line of text.split("\n")) {
    const list = line.match(LIST_PREFIX);
    if (line.trim() === "") {
      flush();
      out.push("");
    } else if (list) {
      flush();
      if (!isInternalRef(line)) out.push(line);
      else {
        const kept = filterSentences(list[2]);
        if (kept !== "") out.push(list[1] + kept);
      }
    } else if (/^\s*(#|\|)/.test(line)) {
      flush();
      if (!isInternalRef(line)) out.push(line);
    } else {
      para.push(line);
    }
  }
  flush();
  return out.join("\n").replace(/\n{3,}/g, "\n\n");
}

const PATH_TOKEN = /(?:^|[\s`(])((?:scripts|docs|skills|agents|tests|\.claude|\.gemini|\.agents)\/[\w./-]*[\w])/g;

/** Paths named in a dependency line, trailing dots trimmed. */
export function pathsInLine(line: string): string[] {
  const out: string[] = [];
  for (const m of line.matchAll(PATH_TOKEN)) out.push(m[1].replace(/\.+$/, ""));
  return out;
}

