import { describe, test, expect, afterAll } from "bun:test";
import { existsSync, unlinkSync, readFileSync, writeFileSync } from "fs";
import { resolve } from "path";
import { $ } from "bun";

const TEST_TOKENS_JSON = resolve(import.meta.dir, "test-tokens.json");
const TEST_CSS = resolve(import.meta.dir, "test-tokens.css");
const TEST_TS = resolve(import.meta.dir, "test-tokens.ts");

describe("scripts/compile-tokens.ts Unit Tests", () => {
  afterAll(() => {
    if (existsSync(TEST_TOKENS_JSON)) unlinkSync(TEST_TOKENS_JSON);
    if (existsSync(TEST_CSS)) unlinkSync(TEST_CSS);
    if (existsSync(TEST_TS)) unlinkSync(TEST_TS);
  });

  test("--help flag outputs usage documentation", async () => {
    const { stdout, exitCode } = await $`bun scripts/compile-tokens.ts --help`.nothrow();
    expect(exitCode).toBe(0);
    expect(stdout.toString()).toContain("Visual Design Tokens Compiler");
  });

  test("compiles tokens.json into CSS Custom Properties and TS Constants", async () => {
    const sampleTokens = {
      color: {
        primary: { value: "#007acc" },
        secondary: { value: "#333333" },
      },
    };
    writeFileSync(TEST_TOKENS_JSON, JSON.stringify(sampleTokens, null, 2), "utf-8");

    const { exitCode } = await $`bun scripts/compile-tokens.ts --input ${TEST_TOKENS_JSON} --output-css ${TEST_CSS} --output-ts ${TEST_TS}`.nothrow();
    expect(exitCode).toBe(0);
    expect(existsSync(TEST_CSS)).toBe(true);
    expect(existsSync(TEST_TS)).toBe(true);

    const cssContent = readFileSync(TEST_CSS, "utf-8");
    expect(cssContent).toContain("--color-primary: #007acc;");
  });

  // U-20261027-006: one VERSION constant feeds EVERY provenance banner.
  test("help, CSS, and TS banners all carry the SAME version string", async () => {
    const help = await $`bun scripts/compile-tokens.ts --help`.nothrow();
    const helpVersion = help.stdout.toString().match(/Visual Design Tokens Compiler v(\d+\.\d+\.\d+)/)?.[1];
    expect(helpVersion).toBeDefined();

    writeFileSync(TEST_TOKENS_JSON, JSON.stringify({ color: { primary: "#000000" } }, null, 2), "utf-8");
    const run = await $`bun scripts/compile-tokens.ts --input ${TEST_TOKENS_JSON} --output-css ${TEST_CSS} --output-ts ${TEST_TS}`.nothrow();
    expect(run.exitCode).toBe(0);

    const css = readFileSync(TEST_CSS, "utf-8");
    const ts = readFileSync(TEST_TS, "utf-8");
    const cssVersion = css.match(/Generated by compile-tokens\.ts v(\d+\.\d+\.\d+)/)?.[1];
    const tsVersion = ts.match(/Generated by compile-tokens\.ts v(\d+\.\d+\.\d+)/)?.[1];
    expect(cssVersion).toBe(helpVersion);
    expect(tsVersion).toBe(helpVersion);
  });

  // U-20261027-005 (DESIGN-R2): theme presets override ONLY color/shadow.
  test("theme preset overriding typography is a HARD error naming preset + key path, with no output written", async () => {
    // Clear artifacts from earlier tests — this test asserts none are written.
    if (existsSync(TEST_CSS)) unlinkSync(TEST_CSS);
    if (existsSync(TEST_TS)) unlinkSync(TEST_TS);
    writeFileSync(
      TEST_TOKENS_JSON,
      JSON.stringify({
        color: { primary: "#000000" },
        themes: {
          dark: {
            color: { primary: "#ffffff" },
            typography: { "font-size-base": "1rem" },
          },
        },
      }),
      "utf-8",
    );
    const { exitCode, stderr } = await $`bun scripts/compile-tokens.ts --input ${TEST_TOKENS_JSON} --output-css ${TEST_CSS} --output-ts ${TEST_TS}`.nothrow();
    expect(exitCode).toBe(1);
    const err = stderr.toString();
    expect(err).toContain('"dark"');
    expect(err).toContain("typography");
    expect(err).toContain("themes.dark.typography");
    expect(err).toContain("color and shadow");
    // The compiler must not write rule violations — no output artifacts.
    expect(existsSync(TEST_CSS)).toBe(false);
    expect(existsSync(TEST_TS)).toBe(false);
  });

  test("theme preset overriding borderRadius (camelCase) is also rejected", async () => {
    writeFileSync(
      TEST_TOKENS_JSON,
      JSON.stringify({
        color: { primary: "#000000" },
        themes: {
          compact: { borderRadius: { sm: "2px" } },
        },
      }),
      "utf-8",
    );
    const { exitCode, stderr } = await $`bun scripts/compile-tokens.ts --input ${TEST_TOKENS_JSON} --output-css ${TEST_CSS} --output-ts ${TEST_TS}`.nothrow();
    expect(exitCode).toBe(1);
    expect(stderr.toString()).toContain("borderRadius");
  });

  test("color/shadow-only theme presets compile to [data-theme] blocks", async () => {
    writeFileSync(
      TEST_TOKENS_JSON,
      JSON.stringify({
        color: { primary: "#000000", surface: "#ffffff" },
        shadow: { sm: "0 1px 2px rgba(0,0,0,0.1)" },
        themes: {
          dark: {
            color: { primary: "#ffffff", surface: "#111111" },
            shadow: { sm: "0 1px 2px rgba(0,0,0,0.5)" },
          },
        },
      }),
      "utf-8",
    );
    const { exitCode } = await $`bun scripts/compile-tokens.ts --input ${TEST_TOKENS_JSON} --output-css ${TEST_CSS} --output-ts ${TEST_TS}`.nothrow();
    expect(exitCode).toBe(0);
    const css = readFileSync(TEST_CSS, "utf-8");
    expect(css).toContain('[data-theme="dark"]');
    expect(css).toContain("--color-primary: #ffffff;");
  });
});
